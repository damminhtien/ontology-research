from pathlib import Path
from typing import Annotated

from fastapi import APIRouter, Depends, HTTPException, Query

from foundry.console.api.monitor import event_log_path
from foundry.console.api.provenance_access import (
    ProvenanceScope,
    provenance_scope,
    visible_source_ids,
)
from foundry.events import EventLog
from foundry.postgres import PostgresDatabase
from foundry.postgres_readmodel import PostgresReadModelStore
from foundry.projector import Projector, replay_log
from foundry.query_service import DEFAULT_TIMEOUT_MS, QueryPage, QueryService
from foundry.readmodel import ReadModel, ReadModelStore, format_instant, parse_instant

BENCHMARK_REPORT = Path(__file__).resolve().parents[3] / "build" / "benchmark-report.json"

router = APIRouter(prefix="/projection", tags=["projection"])


@router.get("/benchmark")
def projection_benchmark() -> dict:
    """Return the latest benchmark report generated by `tools/benchmark.py`."""
    if not BENCHMARK_REPORT.exists():
        raise HTTPException(
            status_code=404,
            detail="No benchmark report found; run `make benchmark` first",
        )
    try:
        return json.loads(BENCHMARK_REPORT.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise HTTPException(status_code=500, detail=f"corrupt benchmark report: {exc}") from exc


_model_cache: ReadModel | None = None
_model_log_fingerprint: tuple[tuple[str, int, int], ...] | None = None
_model_lock = threading.Lock()


def _snapshot_paths(log_path: Path) -> tuple[Path, Path]:
    """Sidecar paths next to the log: pickled model + its fingerprint meta."""
    return (
        log_path.with_suffix(log_path.suffix + ".readmodel.pkl"),
        log_path.with_suffix(log_path.suffix + ".readmodel.json"),
    )


def _read_model() -> ReadModelStore:
    """Read model cached in-process and on disk, resumed incrementally.

    With ``FOUNDRY_DATABASE_URL``, reads use the PostgreSQL projection directly;
    the independent projector worker owns replay and checkpoint updates. Without
    it, local development retains the pickle-backed in-memory scaffold.

    In-memory layers:
    1. in-process cache keyed by log mtime — the common hit;
    2. persisted snapshot + checkpoint (B2/B6): a log change applies only the
       suffix after the recorded sequence, and a server restart loads the
       snapshot instead of replaying the whole log;
    3. anything missing or corrupt degrades to a full replay — the snapshot is
       a cache, never a source of truth (ADR-0002/0004).
    """
    global _model_cache, _model_log_fingerprint
    dsn = os.environ.get("FOUNDRY_DATABASE_URL")
    if dsn:
        return PostgresReadModelStore(PostgresDatabase(dsn))
    with _model_lock:
        path = event_log_path()
        log = EventLog(path)
        fingerprint = log.fingerprint()
        if not fingerprint:
            _model_cache = ReadModel()
            _model_log_fingerprint = None
            return _model_cache

        if _model_cache is not None and _model_log_fingerprint == fingerprint:
            return _model_cache

        snapshot_path, meta_path = _snapshot_paths(path)
        model = ReadModel.load_snapshot(snapshot_path)
        meta: dict = {}
        if model is not None and snapshot_path.exists():
            try:
                meta = json.loads(meta_path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                meta = {}

        checkpoint = model.checkpoint_sequence if model is not None else None
        previous_segments = meta.get("segments")
        current_segments = [list(segment) for segment in fingerprint]
        active_grew = (
            isinstance(previous_segments, list)
            and len(previous_segments) == len(current_segments)
            and bool(current_segments)
            and previous_segments[:-1] == current_segments[:-1]
            and isinstance(previous_segments[-1], list)
            and len(previous_segments[-1]) == 3
            and previous_segments[-1][0] == path.as_posix()
            and current_segments[-1][0] == path.as_posix()
            and isinstance(previous_segments[-1][1], int)
            and current_segments[-1][1] > previous_segments[-1][1]
        )
        grew = (
            model is not None
            and checkpoint is not None
            and meta.get("checkpoint_sequence") == checkpoint
            and active_grew
        )
        if grew:
            # append-only growth: fold in only what came after the checkpoint
            events = log.read_all()  # validates the entire log
            Projector(model).replay(events, after_sequence=checkpoint)
        else:
            model, _stats = replay_log(log)

        model.save_snapshot(snapshot_path)
        meta_path.write_text(
            json.dumps(
                {
                    "checkpoint_sequence": model.checkpoint_sequence,
                    "segments": current_segments,
                }
            )
            + "\n",
            encoding="utf-8",
        )
        _model_cache = model
        _model_log_fingerprint = fingerprint
        return _model_cache


def _query_service() -> QueryService:
    """Create a backend-independent query facade over the configured store."""
    return QueryService(_read_model())


def _page_payload(page: QueryPage) -> dict:
    """Serialize shared paging metadata for the projection API."""
    return {
        "total": page.total,
        "limit": page.limit,
        "offset": page.offset,
        "has_more": page.has_more,
        "truncated": page.truncated,
    }


def reset_cache() -> None:
    """Invalidate the cached model (used by tests)."""
    global _model_cache, _model_log_fingerprint
    with _model_lock:
        _model_cache = None
        _model_log_fingerprint = None


@router.get("")
def projection_stats() -> dict:
    """Projection health: counts, freshness, and lag vs the 5s SLO."""
    model = _read_model()
    stats = model.stats()
    lag = stats["lag_seconds"]
    exists = EventLog(event_log_path()).has_data()
    return {
        "exists": exists,
        "slo_lag_seconds": 5,
        "within_slo": None if lag is None else lag <= 5.0,
        **stats,
    }


@router.get("/entities/{entity_id}")
def entity_by_id(
    entity_id: str,
    scope: Annotated[ProvenanceScope, Depends(provenance_scope)],
) -> dict:
    """Q1 point lookup against the read model."""
    query = _query_service()
    view = query.entity_lookup(entity_id)
    if view is None:
        raise HTTPException(status_code=404, detail=f"unknown entity {entity_id}")
    location = query.current_location(entity_id)
    return {
        "entity": {
            "entity_id": view.entity_id,
            "entity_type": view.entity_type,
            "name": view.name,
            "first_seen": view.first_seen,
            "last_event_time": view.last_event_time,
        },
        "current_location": (
            {
                "location_uri": location.location_uri,
                "as_of": location.as_of,
                "source_ids": visible_source_ids(location.source_ids, scope),
            }
            if location
            else None
        ),
    }


@router.get("/lookup")
def entity_lookup(
    name: Annotated[str, Query(min_length=1)],
    limit: Annotated[int, Query(ge=1, le=100)] = 50,
    offset: Annotated[int, Query(ge=0, le=100_000)] = 0,
    sort_by: Annotated[
        str,
        Query(pattern="^(entity_id|name|entity_type|first_seen|last_event_time)$"),
    ] = "entity_id",
    descending: bool = False,
    timeout_ms: Annotated[int, Query(ge=10, le=5_000)] = DEFAULT_TIMEOUT_MS,
) -> dict:
    """Page exact primary-name and alias candidates from the operational index."""
    try:
        page = _query_service().entity_search(
            name,
            limit=limit,
            offset=offset,
            sort_by=sort_by,
            descending=descending,
            timeout_ms=timeout_ms,
        )
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    return {
        "query": name,
        "matches": [
            {
                "entity_id": view.entity_id,
                "entity_type": view.entity_type,
                "name": view.name,
            }
            for view in page.items
        ],
        **_page_payload(page),
    }


@router.get("/entities/{entity_id}/location/as-of")
def location_as_of(
    entity_id: str,
    at: str,
    scope: Annotated[ProvenanceScope, Depends(provenance_scope)],
) -> dict:
    """Q4 temporal query: location of an entity at a given instant."""
    try:
        instant = parse_instant(at)
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    fact = _query_service().location_as_of(entity_id, instant)
    return {
        "entity_id": entity_id,
        "at": format_instant(instant),
        "location": (
            {
                "location_uri": fact.location_uri,
                "as_of": fact.as_of,
                "source_ids": visible_source_ids(fact.source_ids, scope),
            }
            if fact
            else None
        ),
    }


@router.get("/entities/{entity_id}/relationships")
def relationships_as_of(
    entity_id: str,
    scope: Annotated[ProvenanceScope, Depends(provenance_scope)],
    at: str | None = None,
    predicate_iri: str | None = None,
    limit: Annotated[int, Query(ge=1, le=100)] = 50,
    offset: Annotated[int, Query(ge=0, le=100_000)] = 0,
    timeout_ms: Annotated[int, Query(ge=10, le=5_000)] = DEFAULT_TIMEOUT_MS,
) -> dict:
    """Return entity-valued assertions active at one valid-time instant."""
    try:
        instant = parse_instant(at) if at else datetime.now(UTC)
        page = _query_service().relationships_as_of(
            entity_id,
            instant,
            predicate_iri=predicate_iri,
            limit=limit,
            offset=offset,
            timeout_ms=timeout_ms,
        )
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    rows = [_visible_assertion(row, scope) for row in page.items]
    return {
        "entity_id": entity_id,
        "at": format_instant(instant),
        "relationships": rows,
        **_page_payload(page),
    }


@router.get("/entities/{entity_id}/traverse")
def traverse_relationships(
    entity_id: str,
    at: str,
    scope: Annotated[ProvenanceScope, Depends(provenance_scope)],
    max_hops: Annotated[int, Query(ge=1, le=3)] = 1,
    predicate_iri: str | None = None,
    limit: Annotated[int, Query(ge=1, le=100)] = 50,
    offset: Annotated[int, Query(ge=0, le=100_000)] = 0,
    timeout_ms: Annotated[int, Query(ge=10, le=5_000)] = DEFAULT_TIMEOUT_MS,
) -> dict:
    """Return bounded shortest-path discovery results over active relations."""
    try:
        instant = parse_instant(at)
        page = _query_service().traverse_relationships(
            entity_id,
            instant,
            max_hops=max_hops,
            predicate_iri=predicate_iri,
            limit=limit,
            offset=offset,
            timeout_ms=timeout_ms,
        )
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    return {
        "entity_id": entity_id,
        "at": format_instant(instant),
        "paths": [
            {
                "nodes": list(path.nodes),
                "assertions": [_visible_assertion(row, scope) for row in path.assertions],
                "hops": path.hops,
            }
            for path in page.items
        ],
        **_page_payload(page),
    }


@router.get("/entities/{entity_id}/contradictions")
def entity_contradictions(
    entity_id: str,
    predicate_iri: str,
    at: str,
    scope: Annotated[ProvenanceScope, Depends(provenance_scope)],
    limit: Annotated[int, Query(ge=1, le=100)] = 50,
    offset: Annotated[int, Query(ge=0, le=100_000)] = 0,
    timeout_ms: Annotated[int, Query(ge=10, le=5_000)] = DEFAULT_TIMEOUT_MS,
) -> dict:
    """Return competing distinct values active for one relation."""
    try:
        instant = parse_instant(at)
        page = _query_service().contradictions(
            entity_id,
            predicate_iri,
            instant,
            limit=limit,
            offset=offset,
            timeout_ms=timeout_ms,
        )
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc)) from exc
    contradictions = []
    for item in page.items:
        alternatives = [
            {
                **alternative,
                "assertions": [_visible_assertion(row, scope) for row in alternative["assertions"]],
            }
            for alternative in item["alternatives"]
        ]
        contradictions.append({**item, "alternatives": alternatives})
    return {"contradictions": contradictions, **_page_payload(page)}


@router.get("/assertions/{assertion_id}")
def assertion_provenance(
    assertion_id: str,
    scope: Annotated[ProvenanceScope, Depends(provenance_scope)],
    timeout_ms: Annotated[int, Query(ge=10, le=5_000)] = DEFAULT_TIMEOUT_MS,
) -> dict:
    """Return a source-scoped assertion record with locators and spans."""
    assertion = _query_service().assertion_provenance(assertion_id, timeout_ms=timeout_ms)
    if assertion is None:
        raise HTTPException(status_code=404, detail=f"unknown assertion {assertion_id}")
    return _visible_assertion(assertion, scope)


